#Requires -Version 5.1
<#
.SYNOPSIS
    Generates CloudBox version artifacts from the single source of truth: ./VERSION

.DESCRIPTION
    Every file written by this script is generated. Never hand-edit them; edit VERSION instead.

    VERSION format: MAJOR.MINOR.DD.MM.YY  (e.g. 0.01.13.11.26 = 2026-11-13)
    See docs/decisions/0001-versioning.md.

.PARAMETER Check
    Do not write. Exit 1 if any generated artifact is missing or stale (used in CI).

.EXAMPLE
    pwsh eng/version.ps1

.EXAMPLE
    pwsh eng/version.ps1 -Check
#>
[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$LF = "`n"

function Write-LfFile {
    param([string]$Path, [string]$Content)
    $dir = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Force -Path $dir | Out-Null
    }
    [System.IO.File]::WriteAllText($Path, $Content, (New-Object System.Text.UTF8Encoding($false)))
}

function Read-LfFile {
    param([string]$Path)
    $text = [System.IO.File]::ReadAllText($Path)
    return ($text -replace "`r`n", $LF)
}

# --------------------------------------------------------------------------- parse VERSION
$repoRoot = Split-Path -Parent $PSScriptRoot
$versionPath = Join-Path $repoRoot 'VERSION'

if (-not (Test-Path -LiteralPath $versionPath)) {
    throw "VERSION not found at $versionPath"
}

$version = (Get-Content -LiteralPath $versionPath -Raw).Trim()
$pattern = '^\d+\.\d{2}\.\d{2}\.\d{2}\.\d{2}$'
if ($version -notmatch $pattern) {
    throw "VERSION '$version' does not match MAJOR.MINOR.DD.MM.YY (e.g. 0.01.13.11.26)"
}

$parts  = $version.Split('.')
$major  = [int]$parts[0]
$minor  = [int]$parts[1]
$day    = [int]$parts[2]
$month  = [int]$parts[3]
$year   = 2000 + [int]$parts[4]

try {
    $releaseDate = Get-Date -Year $year -Month $month -Day $day -Hour 0 -Minute 0 -Second 0
} catch {
    throw "VERSION '$version' encodes an invalid date: $day-$month-$year"
}

$releaseDateIso = $releaseDate.ToString('yyyy-MM-dd')
$versionCode    = (($year % 100) * 10000) + ($month * 100) + $day   # YYMMDD
$pubspecVersion = "$major.$minor.$day+$versionCode"                  # pub: major.minor.patch+build

# --------------------------------------------------------------------------- render artifacts
$generatedGo = @(
    "// Code generated by eng/version.ps1 from VERSION. DO NOT EDIT.",
    "",
    "package version",
    "",
    "// generatedVersion is the release version encoded in VERSION.",
    "const generatedVersion = `"$version`"",
    ""
) -join $LF

$generatedDart = @(
    "// Code generated by eng/version.ps1 from VERSION. DO NOT EDIT.",
    "",
    "/// CloudBox release version, in MAJOR.MINOR.DD.MM.YY form.",
    "///",
    "/// Source of truth: the repository's VERSION file.",
    "const String kCloudBoxVersion = '$version';",
    "",
    "/// Release date encoded in [kCloudBoxVersion].",
    "const String kCloudBoxReleaseDate = '$releaseDateIso';",
    "",
    "/// Android versionCode derived from the release date (YYMMDD).",
    "const int kCloudBoxVersionCode = $versionCode;",
    "",
    "/// Version the Dart package toolchain can express (pub requires strict semver).",
    "const String kCloudBoxPubspecVersion = '$pubspecVersion';",
    ""
) -join $LF

$artifacts = @(
    @{ Path = (Join-Path $repoRoot 'agent/internal/version/generated.go'); Content = $generatedGo },
    @{ Path = (Join-Path $repoRoot 'app/lib/core/gen/version.dart'); Content = $generatedDart }
)

# --------------------------------------------------------------------------- write or verify
$stale = @()
foreach ($artifact in $artifacts) {
    $relative = $artifact.Path.Substring($repoRoot.Length).TrimStart('\', '/')
    if ($Check) {
        if (-not (Test-Path -LiteralPath $artifact.Path)) {
            Write-Host "stale (missing): $relative"
            $stale += $relative
        } elseif ((Read-LfFile -Path $artifact.Path) -ne $artifact.Content) {
            Write-Host "stale (outdated): $relative"
            $stale += $relative
        }
    } else {
        Write-LfFile -Path $artifact.Path -Content $artifact.Content
        Write-Host "wrote $relative"
    }
}

if ($Check) {
    if ($stale.Count -gt 0) {
        Write-Host ""
        Write-Host "Run 'pwsh eng/version.ps1' and commit the result." -ForegroundColor Yellow
        exit 1
    }
    Write-Host "version artifacts are current ($version)"
    exit 0
}

Write-Host ""
Write-Host "CloudBox $version"
Write-Host "  release date  $releaseDateIso"
Write-Host "  versionCode   $versionCode"
Write-Host "  pubspec       $pubspecVersion"
